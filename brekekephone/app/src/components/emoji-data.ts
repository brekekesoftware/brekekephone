// Emoji in the BMP (cp <= 0xffff) need the emoji variation selector 0xfe0f to
// render in color instead of a monochrome text glyph. Emoji in the
// supplementary planes (cp >= 0x1f000) are emoji-presentation by default.
export const toEmoji = (cp: number): string =>
  cp <= 0xffff ? String.fromCodePoint(cp, 0xfe0f) : String.fromCodePoint(cp)

